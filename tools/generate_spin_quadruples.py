"""Extract spin-orbital CCSDTQ diagrams from the pinned pdaggerq example."""
import argparse
import ast
from collections import defaultdict
from fractions import Fraction
from itertools import permutations, product
from pathlib import Path


def parity(order):
    return (-1) ** sum(i > j for p, i in enumerate(order) for j in order[p + 1:])


def polynomial(node):
    """Flatten the linear expression used in an upstream residual assignment."""
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.Add):
        yield from polynomial(node.left)
        yield from polynomial(node.right)
    else:
        yield Fraction(ast.literal_eval(node.left)).limit_denominator(144), node.right


def contractions(source, rank):
    name = ("singles", "doubles", "triples", "quadruples")[rank - 1]
    function = next(node for node in source.body
                    if isinstance(node, ast.FunctionDef) and node.name == name + "_residual")
    for statement in function.body:
        if not isinstance(statement, (ast.Assign, ast.AugAssign)):
            continue
        if isinstance(statement, ast.Assign) and statement.targets[0].id == "contracted_intermediate":
            (intermediate,) = polynomial(statement.value)
            continue
        for coefficient, call in polynomial(statement.value):
            if isinstance(call, ast.Name):
                scale, call = intermediate
                coefficient *= scale
            elif isinstance(call.args[1], ast.Name) and call.args[1].id == "contracted_intermediate":
                scale, original = intermediate
                before, after = call.args[0].value.split("->")
                coefficient *= scale * parity(tuple(before.index(c) for c in after))
                call = original
            spec = call.args[0].value
            names = []
            for argument in call.args[1:]:
                expression = argument.value if isinstance(argument, ast.Subscript) else argument
                if expression.id in ("f", "g"):
                    expression = expression.id + "".join(index.id for index in argument.slice.elts)
                else:
                    expression = expression.id
                names.append(expression)
            if "t1" in names:
                continue
            yield coefficient, spec, tuple(names)


def orbital_kinds(subscripts, names):
    kinds = {}
    for letters, name in zip(subscripts, names):
        if name.startswith("t"):
            half = len(letters) // 2
            spaces = "v" * half + "o" * half
        else:
            spaces = name[1:]
        for letter, kind in zip(letters, spaces):
            if kinds.setdefault(letter, kind) != kind:
                raise ValueError(f"Inconsistent orbital type for {letter}")
    return kinds


def canonical(spec, names):
    lhs, output = spec.split("->")
    inputs = lhs.split(",")
    kinds = orbital_kinds(inputs, names)
    rank = len(output) // 2
    internal = [sorted(c for c in kinds if c not in output and kinds[c] == kind)
                for kind in "vo"]
    outside = output[:rank], output[rank:]
    best, phase = None, None
    orders = [tuple(permutations(group)) for group in (*outside, *internal)]
    letters = "".join(outside) + "".join("".join(group) for group in internal)
    for perm in product(*orders):
        new = "".join("".join(group) for group in perm)
        mapping = dict(zip(new, letters))
        sign = parity(perm[0]) * parity(perm[1])
        operands = []
        for name, indices in zip(names, inputs):
            axes = "".join(mapping[c] for c in indices)
            if name[0] != "f":
                half = len(axes) // 2
                a, b = axes[:half], axes[half:]
                sign *= parity(a) * parity(b)
                ordering = sorted(range(half), key=a.__getitem__) + sorted(
                    range(half, 2 * half), key=axes.__getitem__)
                axes = "".join(axes[i] for i in ordering)
                if name.startswith("g"):
                    name = "g" + "".join(name[1 + i] for i in ordering)
            operands.append((name, axes))
        key = tuple(sorted(operands)), output
        if best is None or key < best:
            best, phase = key, sign
        elif key == best and phase != sign:
            phase = 0
    return best, phase


def generate(source):
    tree = ast.parse(source)
    lines = ['"""T1-dressed spin-orbital CCSDTQ diagrams from pdaggerq (Apache-2.0).',
             "", "Generated by tools/generate_spin_quadruples.py. See THIRD_PARTY.md.",
             "Each product is followed by a normalized external antisymmetrizer.",
             '"""', "", "DIAGRAMS = {"]
    for rank in (1, 2, 3, 4):
        accumulated = defaultdict(Fraction)
        cache = {}
        for weight, spec, names in contractions(tree, rank):
            if (spec, names) not in cache:
                cache[spec, names] = canonical(spec, names)
            key, phase = cache[spec, names]
            accumulated[key] += weight * phase
        lines.append(f"    {rank}: (")
        for (operands, output), weight in sorted(accumulated.items()):
            if weight:
                spec = ",".join(axes for _, axes in operands) + "->" + output
                names = tuple(name for name, _ in operands)
                lines.append(f"        ({float(weight)!r}, {spec!r}, {names!r}),")
        lines.append("    ),")
    return "\n".join(lines + ["}", ""])


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("upstream", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.write_text(generate(args.upstream.read_text(encoding="utf-8")), encoding="utf-8")
