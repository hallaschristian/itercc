def _antisymmetrize(tensor, first):
    # A3 = (1 - P12 - P13) (1 - P23) / 6.
    r = tensor - tensor.swapaxes(first + 1, first + 2)
    out = r.copy()
    out -= r.swapaxes(first, first + 1)
    out -= r.swapaxes(first, first + 2)
    out /= 6.0
    return out
